// Pre-built rects per icon: one <rect> per horizontal run, so a 9×9 icon
// is a handful of elements, not 81.
const RUNS = Object.fromEntries(Object.entries(ART).map(([name, rows]) => {
  const runs = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") { x++; continue; }
      const start = x;
      while (x < row.length && row[x] === "#") x++;
      runs.push([start, y, x - start]);
    }
  });
  return [name, runs];
}));

export function PixelIcon({ name, style, className, title }) {
  return (
    <svg
      viewBox="0 0 9 9" aria-hidden={title ? undefined : "true"} role={title ? "img" : undefined}
      className={className}
      style={{
        width: "calc(var(--p) * 9)", height: "calc(var(--p) * 9)",
        display: "inline-block", verticalAlign: "middle", flexShrink: 0,
        shapeRendering: "crispEdges", fill: "currentColor", ...style,
      }}
    >
      {title && <title>{title}</title>}
      {RUNS[name].map(([x, y, w], i) => <rect key={i} x={x} y={y} width={w} height={1} />)}
    </svg>
  );
}

const make = (name) => {
  const Icon = ({ style, className }) => <PixelIcon name={name} style={style} className={className} />;
  Icon.displayName = `Pixel(${name})`;
  return Icon;
};

